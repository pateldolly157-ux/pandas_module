import pandas as pd

data = {
    "ProductName": ["Mobile", "Laptop", "Headphones", "Smartwatch"],
    "Price": [15000, 45000, 2000, 3000],
    "Qty": [2, 1, 3, 2]
}

df = pd.DataFrame(data)

df["TotalValue"] = df["Price"] * df["Qty"]

print(df)

df.to_csv("flipkart_sales.csv", index=False)

data = {
    "Item": ["Pizza", "Burger", "Sandwich", "Pasta"],
    "Price": [200, 100, 150, 250],
    "Qty": [2, 3, 1, 2]
}

df = pd.DataFrame(data)

df["DiscountedPrice"] = df["Price"].apply(lambda x: x * 0.90)

print(df)

data = {
    "PostID": [101, 102, 103],
    "Likes": [1500, 2000000, 850],
    "Comments": [1200, 500000, 75]
}

df = pd.DataFrame(data)

def format_number(n):
    if n >= 1000000:
        return str(round(n / 1000000, 1)) + "M"
    elif n >= 1000:
        return str(round(n / 1000, 1)) + "K"
    else:
        return str(n)

df[["Likes", "Comments"]] = df[["Likes", "Comments"]].applymap(format_number)

print(df)

data = {
    "Restaurant": ["Pizza Hut", "Dominos", "McDonalds", "Subway"],
    "Price": [200, 300, 150, 180],
    "Qty": [2, 1, 3, 2],
    "DeliveryCharge": [30, 40, 25, 20]
}

df = pd.DataFrame(data)

df["FinalAmount"] = df.apply(
    lambda row: (row["Price"] * row["Qty"]) + row["DeliveryCharge"],
    axis=1
)

print(df)

