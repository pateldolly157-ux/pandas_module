from scipy.stats import zscore

def find_outliers(df):
    df["z_score"] = zscore(df["transaction_amount"])
    outliers = df[df["z_score"].abs() > 2]
    return outliers

data = {
    "transaction_id": [101, 102, 103, 104, 105, 106],
    "transaction_amount": [100, 150, 120, 130, 110, 1000]
}

df = pd.DataFrame(data)

result = find_outliers(df)

print("Outlier transactions:")
print(result)