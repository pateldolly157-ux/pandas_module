import pandas as pd

data = {
    'team': ['CSK', 'MI', 'CSK', 'RCB', 'MI', 'RCB'],
    'runs': [180, 160, 200, 175, 190, 185]
}

df = pd.DataFrame(data)

result = df.groupby('team')['runs'].sum().reset_index()

print(result)

data = {
    'city': ['Ahmedabad', 'Mumbai', 'Ahmedabad', 'Mumbai', 'Delhi'],
    'restaurant': ['Food Hub', 'Spice House', 'Food Hub',
                   'Spice House', 'Food Hub'],
    'order_amount': [300, 500, 400, 700, 350]
}

df = pd.DataFrame(data)

result = df.groupby(['city', 'restaurant']).agg(
    average_order_amount=('order_amount', 'mean')
)

print(result)

data = {
    'category': ['Mobile', 'Laptop', 'Mobile', 'Laptop', 'Mobile'],
    'region': ['West', 'North', 'West', 'North', 'South'],
    'sales': [20000, 50000, 30000, 40000, 25000],
    'units_sold': [10, 5, 15, 8, 12]
}

df = pd.DataFrame(data)

result = df.groupby(['category', 'region']).agg(
    total_sales=('sales', 'sum'),
    average_units_sold=('units_sold', 'mean')
)

print(result)

data = {
    'region': ['West', 'East', 'West', 'East', 'North'],
    'revenue': [5000, 7000, 8000, 4000, 6000]
}

df = pd.DataFrame(data)

result = df.groupby('region').agg({
    'revenue': ['sum', 'max', 'min']
})

print(result)

data = {
    'artist': ['Arijit Singh', 'Ed Sheeran', 'Adele',
               'Arijit Singh', 'Ed Sheeran', 'Adele'],
    'genre': ['Pop', 'Pop', 'Jazz', 'Romantic', 'Pop', 'Jazz'],
    'streams': [1000, 2000, 1500, 3000, 2500, 2500]
}

df = pd.DataFrame(data)

result = df.groupby('genre').agg(
    total_streams=('streams', 'sum'),
    average_streams=('streams', 'mean')
)

result = result.sort_values(by='total_streams', ascending=False)

print(result)